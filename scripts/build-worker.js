// Prepares Cloudflare deployment inputs. No bundler or dependency needed.
//  1. dist/            public site files (same allowlist as server/index.js, plus signin.html)
//  2. worker/sources.js exact text of the rubric and implementation files, so the
//                       frozen implementation_hash is computed from identical bytes
import { readFile, writeFile, mkdir, rm, cp, readdir } from "node:fs/promises";
import { dirname, join, relative } from "node:path";

const root = process.cwd();
const FILES = ["index.html", "signin.html", "workspace.html", "dashboard.html", "demo2.html", "demo3.html", "methodology.html"];
const DIRS = ["css", "js", "data", "docs", "eval"];
const SAFE_NAME = /^[A-Za-z0-9_./-]+$/;

await rm(join(root, "dist"), { recursive: true, force: true });
let copied = 0;
async function copyFile(rel) {
  if (!SAFE_NAME.test(rel) || rel.split("/").some((part) => part.startsWith("."))) return;
  await mkdir(dirname(join(root, "dist", rel)), { recursive: true });
  await cp(join(root, rel), join(root, "dist", rel));
  copied++;
}
async function walk(dir) {
  for (const entry of await readdir(join(root, dir), { withFileTypes: true })) {
    const rel = `${dir}/${entry.name}`;
    if (entry.isDirectory()) await walk(rel);
    else await copyFile(rel);
  }
}
for (const file of FILES) await copyFile(file);
for (const dir of DIRS) await walk(dir);
await writeFile(
  join(root, "dist/_headers"),
  "/*\n  Cache-Control: no-store\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: no-referrer\n",
);

const text = (path) => readFile(join(root, path), "utf8");
const rubric = await text("docs/RFI-PRIORITY-CRITERIA-v0.3.md");
// Order must match makeAgent()'s implementation_hash input exactly.
const sources = await Promise.all(["server/agent.js", "server/extraction.js", "js/demo2-core.js"].map(text));
await writeFile(
  join(root, "worker/sources.js"),
  `// GENERATED by scripts/build-worker.js. Do not edit or commit.\nexport const RUBRIC = ${JSON.stringify(rubric)};\nexport const SOURCE_TEXTS = ${JSON.stringify(sources)};\n`,
);
console.log(`Worker build ready: ${copied} public files in dist/, worker/sources.js generated.`);
